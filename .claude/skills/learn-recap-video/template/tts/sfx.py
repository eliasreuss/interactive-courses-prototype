"""Synthesises the sound effects from scratch with numpy.

Everything here is generated by this script, so there is no third party
licence attached. Files land in public/audio/sfx.

Each file is normalised to the same RMS as the voice lines (-20 dBFS), so the
gain values in src/mix.ts read directly as "dB under the voice".
"""
from pathlib import Path

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parent.parent
SFX = ROOT / "public" / "audio" / "sfx"
SR = 48000
TARGET_RMS_DB = -20.0
rng = np.random.default_rng(7)


def hz(note):
    names = {"C": -9, "C#": -8, "D": -7, "D#": -6, "E": -5, "F": -4, "F#": -3, "G": -2, "G#": -1, "A": 0, "A#": 1, "B": 2}
    return 440.0 * 2 ** ((names[note[:-1]] + 12 * (int(note[-1]) - 4)) / 12)


def t_axis(seconds):
    return np.arange(int(seconds * SR)) / SR


def lowpass(x, cutoff):
    """One pole low pass. cutoff may be a scalar or an array the length of x."""
    cutoff = np.broadcast_to(np.asarray(cutoff, dtype=float), x.shape)
    a = np.exp(-2 * np.pi * cutoff / SR)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(len(x)):
        acc = (1 - a[i]) * x[i] + a[i] * acc
        y[i] = acc
    return y


def highpass(x, cutoff):
    return x - lowpass(x, cutoff)


def normalise(x):
    mono = x if x.ndim == 1 else x.mean(axis=1)
    frame = int(0.01 * SR)
    rms = np.array([np.sqrt(np.mean(mono[i:i + frame] ** 2) + 1e-12) for i in range(0, len(mono), frame)])
    active = rms[rms > rms.max() * 0.01]
    current = 20 * np.log10(np.sqrt(np.mean(active ** 2)))
    x = x * 10 ** ((TARGET_RMS_DB - current) / 20)
    peak = np.abs(x).max()
    return x * (0.89 / peak) if peak > 0.89 else x


def stereo(left, right=None):
    return np.stack([left, left if right is None else right], axis=1)


def fade(x, fade_in, fade_out):
    env = np.ones(len(x))
    n_in, n_out = int(fade_in * SR), int(fade_out * SR)
    if n_in:
        env[:n_in] = np.sin(np.linspace(0, np.pi / 2, n_in)) ** 2
    if n_out:
        env[-n_out:] = np.cos(np.linspace(0, np.pi / 2, n_out)) ** 2
    return x * (env[:, None] if x.ndim == 2 else env)


def tick(freq):
    t = t_axis(0.12)
    body = np.sin(2 * np.pi * freq * t) * np.exp(-t / 0.028)
    air = np.sin(2 * np.pi * freq * 2.01 * t) * np.exp(-t / 0.012) * 0.25
    knock = np.sin(2 * np.pi * 520 * t) * np.exp(-t / 0.018) * 0.5
    attack = np.minimum(1, t / 0.0015)
    x = (body + air + knock) * attack
    return stereo(x)


def whoosh():
    dur = 0.9
    t = t_axis(dur)
    peak_at = 0.5
    env = np.where(t < peak_at, (t / peak_at) ** 2.2, np.exp(-(t - peak_at) / 0.16))
    sweep = 250 + 850 * np.sin(np.pi * np.clip(t / dur, 0, 1)) ** 2
    pan = np.linspace(-0.35, 0.35, len(t))
    noise_l = highpass(lowpass(rng.standard_normal(len(t)), sweep), 90)
    noise_r = highpass(lowpass(rng.standard_normal(len(t)), sweep), 90)
    left = noise_l * env * np.sqrt(0.5 - pan / 2)
    right = noise_r * env * np.sqrt(0.5 + pan / 2)
    return fade(stereo(left, right), 0.01, 0.05)


def bell(freq, t, decay):
    partials = [(1.0, 1.0), (2.0, 0.28), (3.0, 0.08), (4.2, 0.04)]
    x = sum(a * np.sin(2 * np.pi * freq * m * t) * np.exp(-t * m / decay) for m, a in partials)
    return x * np.minimum(1, t / 0.008)


def rise():
    dur = 1.8
    t = t_axis(dur)
    out = np.zeros(len(t))
    for i, note in enumerate(["D4", "F#4", "A4", "D5"]):
        start = int(i * 0.16 * SR)
        seg = bell(hz(note), t[: len(t) - start], 0.9) * (0.7 + 0.1 * i)
        out[start:] += seg
    swell_env = np.sin(np.pi * np.clip(t / 0.9, 0, 1)) ** 2 * (t < 0.9)
    swell = lowpass(rng.standard_normal(len(t)), 900) * swell_env * 0.35
    x = lowpass(out + swell, 3500)
    return fade(stereo(x), 0.005, 0.4)


def resolve():
    dur = 3.6
    t = t_axis(dur)
    chord = ["D3", "A3", "D4", "F#4", "A4"]
    x = sum(bell(hz(n), t, 1.6) * (0.8 if n.endswith("3") else 0.55) for n in chord)
    x = lowpass(x, 2800)
    left = x + 0.15 * np.roll(x, int(0.011 * SR))
    right = x + 0.15 * np.roll(x, int(0.017 * SR))
    return fade(stereo(left, right), 0.004, 0.8)


def main():
    SFX.mkdir(parents=True, exist_ok=True)
    files = {
        SFX / "tick-a.wav": tick(1850),
        SFX / "tick-b.wav": tick(2200),
        SFX / "whoosh.wav": whoosh(),
        SFX / "rise.wav": rise(),
        SFX / "resolve.wav": resolve(),
    }
    for path, audio in files.items():
        sf.write(path, normalise(audio).astype(np.float32), SR, subtype="PCM_24")
        print(f"{path.relative_to(ROOT)}  {len(audio) / SR:.2f}s")


if __name__ == "__main__":
    main()
